import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILES = ['index.html', 'index.js', 'styles.css', 'feedback.js', 'achievements.js', 'pwa.js',
    'manifest.json', 'icon.svg', 'menu-sigil.svg', 'menu-divider.svg'];
const hash = data => createHash('sha256').update(data).digest('hex');

export function buildPwa(root = ROOT, check = false) {
    const template = fs.readFileSync(path.join(root, 'scripts/sw-template.js'), 'utf8');
    const required = Object.fromEntries(FILES.map(file => [file, hash(fs.readFileSync(path.join(root, file)))]));
    const media = ['startmenu.mp3', 'gameplaybackgroundmusic.mp3', 'inspiresoftwareintro.mp4']
        .map(file => hash(fs.readFileSync(path.join(root, file))));
    const build = hash(JSON.stringify(required) + media.join('') + template).slice(0, 12);
    const version = `// Generated by npm run pwa:build.\nwindow.EE_BUILD_ID = '${build}';\n`;
    required['pwa-build.js'] = hash(version);
    const sw = template.replace('__EE_BUILD__', build).replace('__EE_REQUIRED__', JSON.stringify(required, null, 2));
    for (const [file, text] of [['pwa-build.js', version], ['sw.js', sw]]) {
        if (check) {
            if (!fs.existsSync(path.join(root, file)) || fs.readFileSync(path.join(root, file), 'utf8') !== text) {
                throw new Error(`${file} is stale. Run npm run pwa:build and commit both generated files.`);
            }
        } else fs.writeFileSync(path.join(root, file), text);
    }
    return build;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    console.log(`PWA build ${buildPwa(ROOT, process.argv.includes('--check'))}`);
}
