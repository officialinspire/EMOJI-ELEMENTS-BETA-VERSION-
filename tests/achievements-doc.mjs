// Writes the catalog table in ACHIEVEMENTS.md from achievements.js, so the document lists every trigger exactly as
// the code checks it.
//
//   node tests/achievements-doc.mjs           check that ACHIEVEMENTS.md is current (exit 1 if not)
//   node tests/achievements-doc.mjs --write   rewrite the table between the markers

import fs from 'node:fs';
import vm from 'node:vm';

const ROOT = new URL('../', import.meta.url);
const DOC = new URL('ACHIEVEMENTS.md', ROOT);
const START = '<!-- catalog:start (generated by tests/achievements-doc.mjs) -->';
const END = '<!-- catalog:end -->';

export function loadCatalog() {
    const sandbox = { window: {}, localStorage: { getItem: () => null, setItem() {} }, console };
    vm.runInNewContext(fs.readFileSync(new URL('achievements.js', ROOT), 'utf8'), sandbox);
    return { catalog: sandbox.window.Achievements.catalog, categories: sandbox.window.Achievements.categories };
}

// The trigger as the code checks it: the event(s), then the condition (test) or the counted value and its goal
const condition = a => {
    const body = fn => fn.toString().replace(/^\(?[a-z, ]*\)?\s*=>\s*/, '').replace(/\s+/g, ' ').trim();
    return a.goal ? `${body(a.progress)} ≥ ${a.goal}` : body(a.test);
};
const cell = text => String(text).replace(/\|/g, '\\|');

export function renderTable() {
    const { catalog, categories } = loadCatalog();
    const lines = [];
    categories.forEach(([key, label, icon]) => {
        const list = catalog.filter(a => a.cat === key);
        lines.push(`### ${icon} ${label} (${list.length})`, '');
        lines.push('| # | ID | Name | Tier | Description (shown in game) | Event | Exact trigger | Backfill |');
        lines.push('|---|---|---|---|---|---|---|---|');
        list.forEach(a => {
            const n = catalog.indexOf(a) + 1;
            lines.push(`| ${n} | \`${a.id}\` | ${a.icon} ${cell(a.name)}${a.hidden ? ' *(hidden)*' : ''} | ${a.tier} | ${cell(a.desc)} | ${a.on.map(e => `\`${e}\``).join(', ')} | \`${cell(condition(a))}\` | ${a.backfill ? 'yes' : ''} |`);
        });
        lines.push('');
    });
    return `${START}\n\n${lines.join('\n')}\n${END}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
    const doc = fs.readFileSync(DOC, 'utf8');
    const from = doc.indexOf(START);
    const to = doc.indexOf(END);
    if (from < 0 || to < 0) {
        console.error('ACHIEVEMENTS.md has no catalog markers');
        process.exit(1);
    }
    const next = doc.slice(0, from) + renderTable() + doc.slice(to + END.length);
    if (process.argv.includes('--write')) {
        fs.writeFileSync(DOC, next);
        console.log('ACHIEVEMENTS.md catalog written');
    } else if (next !== doc) {
        console.error('ACHIEVEMENTS.md is out of date: run node tests/achievements-doc.mjs --write');
        process.exit(1);
    } else {
        console.log('ACHIEVEMENTS.md catalog is current');
    }
}
