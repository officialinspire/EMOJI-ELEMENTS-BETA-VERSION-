// ------------------------------------------------------------------ source extraction

function skipString(src, i, quote) {
    for (let j = i + 1; j < src.length; j++) {
        if (src[j] === '\\') { j++; continue; }
        if (src[j] === quote) return j + 1;
    }
    throw new Error(`Unterminated string at ${i}`);
}

function skipTemplate(src, i) {
    for (let j = i + 1; j < src.length; j++) {
        if (src[j] === '\\') { j++; continue; }
        if (src[j] === '`') return j + 1;
        if (src[j] === '$' && src[j + 1] === '{') j = scanBalanced(src, j + 1) - 1;
    }
    throw new Error(`Unterminated template at ${i}`);
}

function isRegexStart(src, i) {
    let k = i - 1;
    while (k >= 0 && /\s/.test(src[k])) k--;
    return k < 0 || '(,=:[!&|?{};+-*%<>~^'.includes(src[k]);
}

function skipRegex(src, i) {
    let inClass = false;
    for (let j = i + 1; j < src.length; j++) {
        if (src[j] === '\\') { j++; continue; }
        if (src[j] === '[') inClass = true;
        else if (src[j] === ']') inClass = false;
        else if (src[j] === '/' && !inClass) {
            while (/[a-z]/i.test(src[j + 1])) j++;
            return j + 1;
        }
    }
    throw new Error(`Unterminated regex at ${i}`);
}

// Skips a comment, string, template or regex starting at i; returns the new index or -1.
function skipNonCode(src, i) {
    const ch = src[i];
    const next = src[i + 1];
    if (ch === '/' && next === '/') {
        const end = src.indexOf('\n', i);
        return end < 0 ? src.length : end;
    }
    if (ch === '/' && next === '*') return src.indexOf('*/', i + 2) + 2;
    if (ch === '"' || ch === "'") return skipString(src, i, ch);
    if (ch === '`') return skipTemplate(src, i);
    if (ch === '/' && isRegexStart(src, i)) return skipRegex(src, i);
    return -1;
}

// i points at an opening bracket; returns the index just past its matching close.
function scanBalanced(src, i) {
    let depth = 0;
    for (let j = i; j < src.length;) {
        const skipped = skipNonCode(src, j);
        if (skipped >= 0) { j = skipped; continue; }
        if ('({['.includes(src[j])) depth++;
        if (')}]'.includes(src[j]) && --depth === 0) return j + 1;
        j++;
    }
    throw new Error(`Unbalanced bracket at ${i}`);
}

function extractDeclaration(src, name) {
    const match = new RegExp(`^[ \\t]*(function\\s+${name}\\s*\\(|(const|let|var)\\s+${name}\\s*=)`, 'm').exec(src);
    if (!match) throw new Error(`index.js no longer declares "${name}"; update tests/card-audit.mjs`);
    const start = match.index;
    if (match[1].startsWith('function')) {
        const params = src.indexOf('(', start);
        const body = src.indexOf('{', scanBalanced(src, params));
        return src.slice(start, scanBalanced(src, body));
    }
    for (let j = src.indexOf('=', start) + 1; j < src.length;) {
        const skipped = skipNonCode(src, j);
        if (skipped >= 0) { j = skipped; continue; }
        if ('({['.includes(src[j])) { j = scanBalanced(src, j); continue; }
        if (src[j] === ';') return src.slice(start, j + 1);
        j++;
    }
    throw new Error(`Could not find end of "${name}"`);
}

