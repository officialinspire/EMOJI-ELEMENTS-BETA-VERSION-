function seededRandom(seed) {
    return () => {
        seed = (seed + 0x6D2B79F5) | 0;
        let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
        t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
        return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
}

function loadGame() {
    const src = fs.readFileSync(SOURCE_PATH, 'utf8');
    const blockStart = src.indexOf('const ELEMENTS = {');
    const blockEndMarker = 'window.__CARD_BY_ID = __CARD_BY_ID;';
    const blockEnd = src.indexOf(blockEndMarker);
    if (blockStart < 0 || blockEnd < 0) throw new Error('Catalog block markers not found in index.js');
    const catalogBlock = src.slice(blockStart, blockEnd + blockEndMarker.length);
    const rest = src.slice(0, blockStart) + src.slice(blockEnd + blockEndMarker.length);
    const extracted = GAME_DECLARATIONS.map(name => extractDeclaration(rest, name)).join('\n\n');

    const math = Object.create(Math);
    math.random = seededRandom(20261020);
    const context = vm.createContext({ window: {}, console, Math: math });
    const exportNames = ['ELEMENTS', 'CARD_DATABASE', '__ALL_CARDS', '__CARD_BY_ID', ...GAME_DECLARATIONS];
    const game = vm.runInContext(`${catalogBlock}\n${extracted}\n;({ ${exportNames.join(', ')} })`, context);

    // Rules support, read from the engine code so the audit follows the implementation.
    const body = name => extractDeclaration(rest, name);
    const all = (text, re) => [...text.matchAll(re)].map(m => m[1]);
    const onPlay = /const ON_PLAY_ARTIFACT_EFFECTS = \[([^\]]+)\]/.exec(rest);
    if (!onPlay) throw new Error('Could not find ON_PLAY_ARTIFACT_EFFECTS in index.js');
    const support = {
        instantEffects: new Set(all(body('resolveSpell'), /case '(\w+)':/g)),
        artifactOnPlay: new Set(all(onPlay[1], /'(\w+)'/g)),
        artifactUpkeep: new Set(all(body('processUpkeepEffects'), /case '(\w+)':/g)),
        artifactActivated: new Set(all(body('activateArtifact'), /card\.effect !== '(\w+)'/g)),
        tokenTypes: new Set(Object.keys(game.TOKEN_TYPES).filter(key => key !== 'default')),
        flags: new Set(all(body('resolveSpell'), /card\.(untilEndOfTurn|skipUntap)\b/g)),
        buffTypes: new Set(all(body('resolveSpell'), /buffType === '(\w+)'/g)),
        spellTargets: new Set(all(body('resolveSpell'), /card\.target === '(\w+)'/g)),
        abilities: new Set([
            ...all(rest, /hasAbility\([^,()]+,\s*'(\w+)'\)/g),
            ...all(rest, /abilities\??\.includes\('(\w+)'\)/g)
        ])
    };
    support.artifactEffects = new Set([...support.artifactOnPlay, ...support.artifactUpkeep, ...support.artifactActivated]);

    // JS object literals silently keep the last duplicate key, so check the source text per category.
    const duplicateKeys = [];
    for (const category of Object.keys(game.CARD_DATABASE)) {
        const open = catalogBlock.indexOf('{', catalogBlock.search(new RegExp(`\\n\\s*${category}: \\{`)));
        const text = catalogBlock.slice(open + 1, scanBalanced(catalogBlock, open) - 1);
        const seen = new Set();
        for (const key of all(text, /^\s*(\w+):\s*\{/gm)) {
            if (seen.has(key)) duplicateKeys.push(`${category}.${key}`);
            seen.add(key);
        }
    }
    return { game, support, duplicateKeys };
}

// ------------------------------------------------------------------ audit

const TYPE_FIELDS = {
    land: ['element', 'elements'],
    creature: ['cost', 'power', 'toughness', 'abilities'],
    instant: ['cost', 'effect', 'value', 'buffType', 'grantAbilities', 'target', 'drawCards', 'tokenType', 'untilEndOfTurn', 'skipUntap'],
    artifact: ['cost', 'effect', 'value', 'buffType', 'grantAbilities', 'targetAll']
};
const COMMON_FIELDS = ['emoji', 'type', 'cardType', 'name', 'desc', 'theme', '_category', '__id', '__rarity'];
const CATEGORY_TYPE = { lands: 'land', creatures: 'creature', spells: 'instant', artifacts: 'artifact' };
const CARD_TYPE_PATTERN = { land: /^Land( - (Dual|Universal))?$/, creature: /^Creature$/, instant: /^Instant\/Spell$/, artifact: /^Artifact$/ };
const THEMES = ['Fantasy', 'Science Fiction', 'Nature', 'City'];
// Effect parameter rules: which numeric `value` an effect needs.
const VALUE_RULES = {
    damage: 'positive', heal: 'positive', heal_draw: 'positive', draw: 'positive', draw_on_play: 'positive',
    drain: 'positive', aoe: 'positive', buff_defense: 'positive', discard: 'positive', discard_draw: 'positive',
    token: 'positive', mana: 'positive', buff: 'non-negative', tap: 'none', bounce: 'none', destroy: 'none', revive: 'none'
};

const isInt = n => Number.isInteger(n);
const COLOR_ORDER = ['fire', 'water', 'earth', 'swamp', 'light'];
const byColorOrder = colors => [...colors].sort((a, b) => COLOR_ORDER.indexOf(a) - COLOR_ORDER.indexOf(b));
const costColors = card => byColorOrder(Object.keys(card.cost || {}).filter(key => key !== 'colorless'));
const manaValue = card => Object.values(card.cost || {}).reduce((sum, n) => sum + n, 0);

function audit() {
    const { game, support, duplicateKeys } = loadGame();
    const { ELEMENTS, CARD_DATABASE, __ALL_CARDS: cards, __CARD_BY_ID: byId } = game;
    const findings = []; // { check, id, detail }
    const add = (check, id, detail) => findings.push({ check, id, detail });

    duplicateKeys.forEach(key => add('duplicate-source-key', key, 'object key repeated; the earlier card is silently lost'));
    if (Object.keys(byId).length !== cards.length) add('duplicate-id', '*', `${cards.length} cards but ${Object.keys(byId).length} ids`);

    const nameCounts = {};
    cards.forEach(card => {
        const key = String(card.name).trim().toLowerCase();
        nameCounts[key] = (nameCounts[key] || 0) + 1;
    });

    // ---- per-card data checks
    for (const card of cards) {
        const id = card.__id;
        const type = card.type;
        if (!TYPE_FIELDS[type]) { add('bad-type', id, `type "${type}"`); continue; }
        if (CATEGORY_TYPE[card._category] !== type) add('category-type-mismatch', id, `${card._category} holds a ${type}`);
        if (!CARD_TYPE_PATTERN[type].test(card.cardType || '')) add('bad-card-type-label', id, `cardType "${card.cardType}"`);
        for (const field of Object.keys(card)) {
            if (!COMMON_FIELDS.includes(field) && !TYPE_FIELDS[type].includes(field)) add('unknown-field', id, field);
        }
        if (!String(card.name || '').trim()) add('missing-name', id, '');
        if (!String(card.emoji || '').trim()) add('missing-emoji', id, '');
        if (!String(card.desc || '').trim()) add('missing-desc', id, '');
        if (!THEMES.includes(card.theme)) add('bad-theme', id, `theme "${card.theme}"`);
        if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(id)) add('bad-id', id, 'id must be lowercase slug');
        if (nameCounts[String(card.name).trim().toLowerCase()] > 1) add('duplicate-name', id, card.name);

        if (type === 'land') {
            const produced = [...(card.elements || []), ...(card.element ? [card.element] : [])];
            if (!produced.length || produced.some(e => !ELEMENTS[e])) add('bad-land-mana', id, JSON.stringify(produced));
            if (card.element && card.elements) add('bad-land-mana', id, 'has both element and elements');
            const basic = card.element && card.element !== 'colorless' && !card.elements;
            if (basic && card.__rarity !== 'common') add('basic-land-not-common', id, `inferred ${card.__rarity}`);
            continue;
        }

        const cost = card.cost;
        if (!cost || typeof cost !== 'object') add('bad-cost', id, 'missing cost');
        else {
            Object.entries(cost).forEach(([color, n]) => {
                if (!ELEMENTS[color]) add('bad-cost', id, `unknown cost color "${color}"`);
                if (!isInt(n) || n < 1) add('bad-cost', id, `${color}: ${n}`);
            });
            if (Object.keys(cost).length === 0) add('free-cost', id, 'cost {} (mana value 0)');
            if (costColors(card).length > 2) add('unplayable-colors', id, 'needs 3+ colors; decks hold at most 2');
        }

        if (type === 'creature') {
            if (!isInt(card.power) || card.power < 0) add('bad-stats', id, `power ${card.power}`);
            if (!isInt(card.toughness) || card.toughness < 1) add('bad-stats', id, `toughness ${card.toughness}`);
            if (!Array.isArray(card.abilities)) add('bad-abilities', id, 'abilities must be an array');
            (card.abilities || []).forEach(ability => {
                if (!support.abilities.has(ability)) add('unsupported-ability', id, ability);
            });
            if (new Set(card.abilities).size !== (card.abilities || []).length) add('bad-abilities', id, 'repeated ability');
            continue;
        }

        const supported = type === 'instant' ? support.instantEffects : support.artifactEffects;
        if (!supported.has(card.effect)) { add('unsupported-effect', id, String(card.effect)); continue; }
        const rule = VALUE_RULES[card.effect];
        if (!rule) add('unsupported-effect', id, `no parameter rule for "${card.effect}"; add one to VALUE_RULES`);
        if (rule === 'positive' && !(isInt(card.value) && card.value > 0)) add('bad-effect-value', id, `${card.effect} value ${card.value}`);
        if (rule === 'non-negative' && !(isInt(card.value) && card.value >= 0)) add('bad-effect-value', id, `${card.effect} value ${card.value}`);
        if (card.effect === 'buff' && !card.value && !(card.grantAbilities || []).length) add('bad-effect-value', id, 'buff does nothing');
        if (card.tokenType !== undefined && !support.tokenTypes.has(card.tokenType)) add('bad-effect-param', id, `tokenType ${card.tokenType}`);
        if (card.effect === 'token' && !support.tokenTypes.has(card.tokenType)) add('bad-effect-param', id, `tokenType ${card.tokenType}`);
        if (card.buffType !== undefined && !support.buffTypes.has(card.buffType)) add('bad-effect-param', id, `buffType ${card.buffType}`);
        if (card.target !== undefined && !support.spellTargets.has(card.target)) add('bad-effect-param', id, `target ${card.target}`);
        if (card.drawCards !== undefined && !(isInt(card.drawCards) && card.drawCards > 0)) add('bad-effect-param', id, `drawCards ${card.drawCards}`);
        if (card.targetAll !== undefined && typeof card.targetAll !== 'boolean') add('bad-effect-param', id, 'targetAll must be boolean');
        // Flags the engine reads only for one kind of effect (EFFECTS.md).
        const flagRules = { untilEndOfTurn: c => c.effect === 'buff' && c.buffType === 'power', skipUntap: c => c.effect === 'tap' };
        for (const [flag, fits] of Object.entries(flagRules)) {
            if (card[flag] === undefined) continue;
            if (card[flag] !== true || !fits(card) || !support.flags.has(flag)) add('bad-effect-param', id, `${flag} not supported here`);
        }
        // Card details show describeEffect(card) as the rules line; it must describe every effect.
        const rulesText = game.describeEffect(card);
        if (!rulesText || rulesText === card.desc || /undefined|NaN/.test(rulesText)) add('no-rules-text', id, `describeEffect: "${rulesText}"`);
        (card.grantAbilities || []).forEach(ability => {
            if (!support.abilities.has(ability)) add('unsupported-ability', id, `grants ${ability}`);
        });
    }

    // ---- availability paths, computed with the game's own functions
    const freshMeta = game.createInitialMeta();
    const deckKeys = [...game.STARTER_MONO_DECK_KEYS, ...game.STARTER_DUAL_DECK_KEYS];
    const starterDecksOf = {};
    for (const key of deckKeys) {
        const deck = freshMeta.decks[key];
        if (!deck) { add('starter-deck-missing', key, ''); continue; }
        if (deck.cardIds.length !== game.STANDARD_DECK_SIZE) add('starter-deck-size', key, `${deck.cardIds.length} cards`);
        new Set(deck.cardIds).forEach(id => (starterDecksOf[id] ||= []).push(key));
        const needed = {};
        deck.cardIds.forEach(id => { needed[id] = (needed[id] || 0) + 1; });
        Object.entries(needed).forEach(([id, n]) => {
            if ((freshMeta.collection[id] || 0) < n) add('starter-card-not-owned', id, `${key} needs ${n}, starter collection has ${freshMeta.collection[id] || 0}`);
        });
        const verdict = game.validateDeckBuild(key, deck.cardIds, freshMeta);
        verdict.errors
            .filter(error => !/exceeds owned copies/.test(error)) // reported above as starter-card-not-owned
            .forEach(error => add('starter-deck-invalid', key, error));
    }
    // Saved games: a freshly seeded save must survive a reload unchanged.
    const reloaded = game.validateMeta(JSON.parse(JSON.stringify(freshMeta)));
    for (const key of deckKeys) {
        const before = freshMeta.decks[key]?.cardIds.length;
        const after = reloaded.decks[key]?.cardIds.length;
        if (before !== after) add('starter-deck-shrinks-on-reload', key, `${before} → ${after} cards`);
    }

    // ---- Pack membership (PACK_MEMBERSHIP, reviewed per card) and the pools built from it
    const packKeys = game.PACK_THEMES.map(theme => theme.key);
    const catalogIds = new Set(cards.map(card => card.__id));
    for (const id of Object.keys(game.PACK_MEMBERSHIP)) {
        if (!catalogIds.has(id)) add('pack-membership-unknown-id', id, 'PACK_MEMBERSHIP names a card that is not in the catalog');
    }
    for (const card of cards) {
        const packs = game.PACK_MEMBERSHIP[card.__id];
        if (!Array.isArray(packs) || !packs.length) { add('pack-membership-missing', card.__id, 'no PACK_MEMBERSHIP entry: every card must be in a pack'); continue; }
        packs.filter(key => !packKeys.includes(key)).forEach(key => add('pack-membership-bad-pack', card.__id, `unknown pack "${key}"`));
        if (new Set(packs).size !== packs.length) add('pack-membership-bad-pack', card.__id, 'a pack is listed twice');
        // Lands packs hold lands only, and every land is in them
        if (packs.includes('lands') && card.type !== 'land') add('lands-pack-non-land', card.__id, `${card.type} in the Lands pack`);
        if (card.type === 'land' && !packs.includes('lands')) add('land-not-in-lands-pack', card.__id, 'every land belongs in the Lands pack');
        // The documented defect: aliens and robots must be in their own packs, not only in Science Fiction
        const alienLike = /\b(alien|ufo)\b/i.test(card.name) || ['👽', '🛸'].includes(card.emoji);
        const robotLike = /\b(robot|android|cyborg|mech|drone)\b|bot\b/i.test(card.name) || ['🤖', '🦾', '🦿'].includes(card.emoji);
        if (alienLike && !packs.includes('alien')) add('alien-not-in-alien-pack', card.__id, card.name);
        if (robotLike && !packs.includes('robot')) add('robot-not-in-robot-pack', card.__id, card.name);
    }

    const packPools = {};
    const packThemesOf = {};
    for (const { key } of game.PACK_THEMES) {
        const odds = game.getPackOdds(key);
        const { pool } = odds;
        if (pool.length < game.PACK_SIZE) add('pack-pool-too-small', key, `${pool.length} cards: packs would fall back to the whole catalog`);
        // Every card in a pool can be pulled (exact odds > 0)
        pool.filter(card => !(odds.perCard[game.packTierOf(card)] > 0)).forEach(card => add('pack-card-unreachable', card.__id, `in ${key} but never drawn`));
        // Seeded packs: 5 different cards, all from the pool, each slot from its planned tiers, every card seen
        const seen = new Set();
        for (let i = 0; i < 3000; i++) {
            const ids = game.generatePack(key);
            if (ids.length !== game.PACK_SIZE || new Set(ids).size !== ids.length) { add('pack-generation', key, `pack ${ids.join(',')}`); break; }
            const off = ids.filter(id => !pool.some(card => card.__id === id));
            if (off.length) { add('pack-generation', key, `outside the pool: ${off.join(', ')}`); break; }
            ids.forEach(id => seen.add(id));
        }
        const neverSeen = pool.filter(card => !seen.has(card.__id));
        if (neverSeen.length) add('pack-card-never-drawn', key, `${neverSeen.length} card(s) never drawn in 3000 seeded packs: ${neverSeen.slice(0, 5).map(c => c.__id).join(', ')}`);
        const round = n => Math.round(n * 10000) / 10000;
        packPools[key] = {
            cost: game.PACK_SHOP_COSTS[key],
            size: pool.length,
            byTier: { ...odds.counts },
            slots: game.describePackSlots(key).slots.map(slot => `${slot.count} × ${slot.label}`).join(' · '),
            chancePerCard: Object.fromEntries(Object.entries(odds.perCard).map(([tier, p]) => [tier, round(p)]))
        };
        pool.forEach(card => (packThemesOf[card.__id] ||= []).push(key));
    }
    for (const card of cards) {
        if (!(packThemesOf[card.__id] || []).length) add('not-in-any-pack', card.__id, 'every card must be obtainable from at least one pack');
    }

    const aiSeen = new Set();
    const colorSets = [...game.STARTER_MONO_DECK_KEYS, ...game.STARTER_DUAL_DECK_KEYS].map(game.getDeckColorsFromKey);
    for (const colors of colorSets) {
        for (let i = 0; i < 60; i++) game.generateDeck(colors).forEach(card => card.__id && aiSeen.add(card.__id));
    }

    const legalDecksOf = {};
    for (const card of cards) {
        legalDecksOf[card.__id] = deckKeys.filter(key => {
            const colors = game.getDeckColorsFromKey(key);
            if (!game.isCardEligibleForDeck(card, colors)) return false;
            if (card.type !== 'land') return true;
            // The same land-colour rule validateDeckBuild applies on save.
            return game.inferLandElements(card).some(element => colors.includes(element));
        });
        const acquirable = (freshMeta.collection[card.__id] || 0) > 0 || (packThemesOf[card.__id] || []).length > 0;
        if (!acquirable) add('unobtainable', card.__id, 'not in the starter collection or any pack pool');
        if (!legalDecksOf[card.__id].length) add('not-deck-legal', card.__id, 'cannot be saved in any standard deck');
    }

    // ---- manifest
    const manifestCards = cards.map(card => {
        const params = {};
        ['value', 'buffType', 'grantAbilities', 'target', 'targetAll', 'drawCards', 'tokenType', 'untilEndOfTurn', 'skipUntap']
            .forEach(field => { if (card[field] !== undefined) params[field] = card[field]; });
        return {
            id: card.__id,
            sourceKey: Object.keys(CARD_DATABASE[card._category]).find(key => CARD_DATABASE[card._category][key] === card),
            category: card._category,
            name: card.name,
            emoji: card.emoji,
            type: card.type,
            cardType: card.cardType,
            theme: card.theme,
            rarity: card.__rarity,
            colors: card.type === 'land' ? byColorOrder(game.inferLandElements(card)) : costColors(card),
            cost: card.type === 'land' ? null : card.cost,
            manaValue: card.type === 'land' ? 0 : manaValue(card),
            ...(card.type === 'creature' ? { power: card.power, toughness: card.toughness, abilities: card.abilities } : {}),
            ...(card.effect ? { effect: card.effect, effectParams: params, rules: game.describeEffect(card) } : {}),
            desc: card.desc ?? null,
            deckBuilderCopyLimit: Number.isFinite(game.getDeckBuilderCopyLimit(card)) ? game.getDeckBuilderCopyLimit(card) : 'unlimited',
            availability: {
                starterCollectionCopies: freshMeta.collection[card.__id] || 0,
                starterDecks: starterDecksOf[card.__id] || [],
                packThemes: packThemesOf[card.__id] || [],
                inAiDecks: aiSeen.has(card.__id),
                deckBuilderLegalIn: legalDecksOf[card.__id]
            }
        };
    });

    const tally = (list, keyFn) => list.reduce((acc, item) => {
        [].concat(keyFn(item)).forEach(key => { acc[key] = (acc[key] || 0) + 1; });
        return acc;
    }, {});
    const identity = c => c.colors.length === 0 ? (c.type === 'land' || c.manaValue > 0 ? 'colorless' : 'free (no cost)') : c.colors.length === 5 ? 'any color (Rainbow)' : c.colors.length > 1 ? `multi: ${c.colors.join('+')}` : c.colors[0];
    const counts = {
        total: manifestCards.length,
        byType: tally(manifestCards, c => c.type),
        byColorIdentity: tally(manifestCards, identity),
        creaturesByColorIdentity: tally(manifestCards.filter(c => c.type === 'creature'), identity),
        byThemeField: tally(manifestCards, c => c.theme),
        byPack: tally(manifestCards, c => c.availability.packThemes),
        byPackCount: tally(manifestCards, c => `in ${c.availability.packThemes.length} pack${c.availability.packThemes.length === 1 ? '' : 's'}`),
        byRarity: tally(manifestCards, c => c.rarity),
        byEffect: tally(manifestCards.filter(c => c.effect), c => `${c.type}:${c.effect}`),
        byAbility: tally(manifestCards.filter(c => c.type === 'creature'), c => c.abilities.length ? c.abilities : ['(none)']),
        byManaValue: tally(manifestCards.filter(c => c.type !== 'land'), c => String(c.manaValue)),
        packPools,
        availability: {
            inStarterCollection: manifestCards.filter(c => c.availability.starterCollectionCopies > 0).length,
            inAnyPackPool: manifestCards.filter(c => c.availability.packThemes.length > 0).length,
            packOnly: manifestCards.filter(c => !c.availability.starterCollectionCopies && c.availability.packThemes.length).length,
            inAiDecks: manifestCards.filter(c => c.availability.inAiDecks).length,
            deckBuilderLegalSomewhere: manifestCards.filter(c => c.availability.deckBuilderLegalIn.length).length
        }
    };
    const manifest = {
        // 2: pack membership is explicit (availability.packThemes from PACK_MEMBERSHIP); packTheme removed
        schemaVersion: 2,
        source: 'index.js CARD_DATABASE (ids: `${category}-${slug(name)}`; saved collections/decks key on these ids)',
        counts,
        cards: manifestCards
    };
    return { manifest, findings, support };
}

// ------------------------------------------------------------------ reporting

function countsMarkdown(counts) {
    const table = (title, obj, keyLabel = 'Value') => {
        const rows = Object.entries(obj).sort((a, b) => b[1] - a[1] || String(a[0]).localeCompare(String(b[0])));
        return `**${title}**\n\n| ${keyLabel} | Cards |\n|---|---|\n${rows.map(([k, v]) => `| ${k} | ${v} |`).join('\n')}\n`;
    };
    const pct = p => `${(p * 100).toFixed(p < 0.1 ? 1 : 0)}%`;
    const pools = Object.entries(counts.packPools)
        .map(([key, p]) => `| ${key} | ${p.cost} | ${p.size} | ${p.byTier.common} / ${p.byTier.rare} / ${p.byTier['epic+']} | ${p.slots} | `
            + `${['common', 'rare', 'epic+'].map(t => (p.byTier[t] ? pct(p.chancePerCard[t]) : '–')).join(' / ')} |`).join('\n');
    const a = counts.availability;
    return [
        COUNTS_START,
        `**Total: ${counts.total} cards**: ${Object.entries(counts.byType).map(([k, v]) => `${v} ${k}`).join(', ')}.`,
        '',
        table('By type', counts.byType, 'Type'),
        table('By color identity (cost colors; lands: produced colors)', counts.byColorIdentity, 'Identity'),
        table('Creatures by color identity', counts.creaturesByColorIdentity, 'Identity'),
        table('By `theme` field', counts.byThemeField, 'Theme'),
        table('By pack (`PACK_MEMBERSHIP`; a card can be in several)', counts.byPack, 'Pack'),
        table('Packs per card', counts.byPackCount, 'Packs'),
        table('By inferred rarity (`inferRarity`)', counts.byRarity, 'Rarity'),
        table('By effect (instants and artifacts)', counts.byEffect, 'type:effect'),
        table('By creature ability (a creature counts once per ability)', counts.byAbility, 'Ability'),
        table('By mana value (non-lands)', counts.byManaValue, 'Mana value'),
        '**Pack pools (`getThemePool`, `getPackOdds`)**\n\n| Pack | Cost | Pool size | Common / Rare / Epic+ | Slots | Chance a given card is in a pack (Common / Rare / Epic+) |\n|---|---|---|---|---|---|\n' + pools + '\n',
        `**Availability:** ${a.inStarterCollection} in the starter collection · ${a.inAnyPackPool} in at least one pack pool · ` +
            `${a.packOnly} pack-only · ${a.inAiDecks} can appear in AI decks · ${a.deckBuilderLegalSomewhere} legal in at least one standard deck.`,
        COUNTS_END
    ].join('\n');
}

function updateAuditCounts(markdown, counts) {
    const start = markdown.indexOf(COUNTS_START);
    const end = markdown.indexOf(COUNTS_END);
    if (start < 0 || end < 0) throw new Error('CARD_AUDIT.md is missing the card-counts markers');
    return markdown.slice(0, start) + countsMarkdown(counts) + markdown.slice(end + COUNTS_END.length);
}

function main() {
    const { manifest, findings, support } = audit();
    const manifestJson = JSON.stringify(manifest, null, 2) + '\n';

    if (args.has('--json')) {
        process.stdout.write(manifestJson);
        return;
    }
    if (args.has('--write')) {
        fs.mkdirSync(path.dirname(MANIFEST_PATH), { recursive: true });
        fs.writeFileSync(MANIFEST_PATH, manifestJson);
        fs.writeFileSync(AUDIT_PATH, updateAuditCounts(fs.readFileSync(AUDIT_PATH, 'utf8'), manifest.counts));
        console.log(`Wrote ${path.relative(ROOT, MANIFEST_PATH)} and the counts block in ${path.relative(ROOT, AUDIT_PATH)}.`);
    }

    const errors = [];
    const known = [];
    const seenKnown = new Set();
    for (const finding of findings) {
        if ((KNOWN_ISSUES[finding.check] || []).includes(finding.id)) {
            known.push(finding);
            seenKnown.add(`${finding.check}:${finding.id}`);
        } else {
            errors.push(finding);
        }
    }
    for (const [check, ids] of Object.entries(KNOWN_ISSUES)) {
        ids.filter(id => !seenKnown.has(`${check}:${id}`))
            .forEach(id => errors.push({ check, id, detail: 'listed in KNOWN_ISSUES but no longer reproduces; remove it from the list' }));
    }

    // Manifest drift: removed ids silently drop saved copies (validateMeta discards unknown ids).
    if (!args.has('--write')) {
        if (!fs.existsSync(MANIFEST_PATH)) {
            errors.push({ check: 'manifest', id: '*', detail: 'docs/card-manifest.json missing; run with --write' });
        } else {
            const committed = JSON.parse(fs.readFileSync(MANIFEST_PATH, 'utf8'));
            const oldIds = new Set(committed.cards.map(c => c.id));
            const newIds = new Set(manifest.cards.map(c => c.id));
            [...oldIds].filter(id => !newIds.has(id)).forEach(id => errors.push({
                check: 'card-id-removed', id,
                detail: 'saved collections/decks holding this id would lose it on load; restore the name or add a save migration'
            }));
            const added = [...newIds].filter(id => !oldIds.has(id));
            if (added.length) errors.push({ check: 'manifest-stale', id: added.join(', '), detail: 'new card ids; review, then run --write' });
            if (!added.length && JSON.stringify(committed) !== JSON.stringify(manifest)) {
                const changed = manifest.cards
                    .filter(card => JSON.stringify(card) !== JSON.stringify(committed.cards.find(c => c.id === card.id)))
                    .map(card => card.id);
                errors.push({ check: 'manifest-stale', id: changed.join(', ') || 'counts', detail: 'catalog changed; review the diff, then run --write' });
            }
            const markdown = fs.existsSync(AUDIT_PATH) ? fs.readFileSync(AUDIT_PATH, 'utf8') : '';
            if (!markdown.includes(countsMarkdown(manifest.counts))) {
                errors.push({ check: 'audit-counts-stale', id: 'CARD_AUDIT.md', detail: 'counts block out of date; run --write' });
            }
        }
    }

    const c = manifest.counts;
    console.log(`Catalog: ${c.total} cards (${Object.entries(c.byType).map(([k, v]) => `${v} ${k}`).join(', ')})`);
    console.log(`Rarity: ${Object.entries(c.byRarity).map(([k, v]) => `${k} ${v}`).join(', ')}`);
    console.log(`Supported abilities (from engine): ${[...support.abilities].sort().join(', ')}`);
    console.log(`\nKnown issues awaiting a decision: ${known.length}`);
    const groupedKnown = {};
    known.forEach(f => (groupedKnown[f.check] ||= []).push(`${f.id}${f.detail ? ` (${f.detail})` : ''}`));
    Object.entries(groupedKnown).forEach(([check, items]) => console.log(`  ~ ${check}: ${items.join('; ')}`));
    if (errors.length) {
        console.log(`\n❌ ${errors.length} problem(s):`);
        errors.forEach(f => console.log(`  ✗ [${f.check}] ${f.id}${f.detail ? `: ${f.detail}` : ''}`));
        process.exit(1);
    }
    console.log('\n✅ Card catalog checks passed.');
}

main();
